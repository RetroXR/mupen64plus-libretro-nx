#!/usr/bin/env python3
"""Generate vru_word_table.h from Rosalie's Mupen GUI's VRUwords.cpp.

The VRU sends each word as a sequence of big-endian uint16 phoneme codes. The
table maps the hex form of that sequence to the text a speech recognizer is
asked to listen for. Both games' vocabularies are in it, including Densha de
GO!'s Shift-JIS words, which RMG maps to English text -- which is why one
English model serves both.

    python tools/gen_vru_word_table.py --src VRUwords.cpp \
        --out custom/mupen64plus-core/plugin/vru_word_table.h --rev <sha>

Transcribed rather than hand-copied because 717 entries typed out are wrong.
"""
